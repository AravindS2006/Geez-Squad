import type { ArmMode, ExerciseDefinition, LibraryExerciseId } from './exercise-library';
import type { Arms } from './rep-events';
export type ExerciseId = LibraryExerciseId;
export type Person = { id: string; name: string; email: string; role: string; goal: string };
export type Block = {
  id?: string;
  exercise: ExerciseId;
  sets: number;
  reps: number;
  rest: number;
  loadKg?: number;
  loadBasis?: 'per-hand' | 'total';
  armMode?: ArmMode;
  targetUnit?: 'reps' | 'seconds';
};
export type Plan = {
  id: string;
  name: string;
  description: string;
  blocks: Block[];
  canEdit?: boolean;
};
export type MetricView = {
  targetUnit?: 'reps' | 'seconds';
  armMode?: ArmMode | null;
  arms?: Arms | null;
  technique?: string | null;
  blockId?: string | null;
  measurementSource?: 'automatic' | 'manual' | 'timer';
  exercise: string;
  revision: number;
  reps: number;
  holdSeconds: number;
  score: number | null;
  confidence: number;
  phase: string;
  cue: string;
  quality?: number | null;
  rangeDegrees?: number | null;
  repSeconds?: number | null;
  trackingCoverage?: number | null;
  rejectedReps?: number;
  updatedAt: string;
};
export type ClientView = Person & {
  assignedAt?: string | null;
  joinedAt: string;
  coachNote?: string;
  latestCheckIn?: CheckInView | null;
  lastTrainingAt?: string | null;
  completedSetsThisWeek?: number;
};
export type WorkoutSetRecord = {
  exerciseLabel?: string;
  schemaVersion?: number;
  runId?: string | null;
  blockId?: string | null;
  armMode?: ArmMode | null;
  arms?: Arms | null;
  measurementSource?: 'automatic' | 'manual' | 'timer';
  targetUnit?: 'reps' | 'seconds';
  loadBasis?: 'per-hand' | 'total' | null;
  clientId: string;
  classId: string | null;
  revision: number;
  exercise: ExerciseId;
  ruleVersion: string;
  setNumber: number;
  target: number;
  reps: number;
  holdMs: number;
  activeMs: number;
  trackedMs: number;
  formScore: number | null;
  qualityScore: number | null;
  rangeDegrees: number | null;
  repSeconds: number | null;
  confidence: number | null;
  rejectedReps: number;
  loadKg: number | null;
  completed: boolean;
  startedAt: string;
  endedAt: string;
};
export type WorkoutSetView = WorkoutSetRecord & {
  originalReps?: number;
  correction?: {
    reps: number;
    holdMs: number;
    reason: string;
    actorId: string;
    createdAt: string;
  } | null;
  id: string;
  userId: string;
  userName: string;
  classTitle: string | null;
};
export type CheckInView = {
  id: string;
  userId: string;
  userName: string;
  energy: number;
  soreness: number;
  effort: number | null;
  sleepHours: number | null;
  bodyweightKg: number | null;
  note: string;
  createdAt: string;
};
export type AssignmentView = { userId: string; planId: string; assignedAt: string };
export type ClassView = {
  activeBlockId?: string | null;
  controlSequence?: number;
  permissions?: { canManage: boolean; hostId: string; presenterIds?: string[] };
  id: string;
  editVersion?: string;
  title: string;
  startsAt: string;
  duration: number;
  capacity: number;
  participantCount?: number;
  status: string;
  exercise: ExerciseId;
  revision: number;
  paused: boolean;
  startedAt: string | null;
  endedAt: string | null;
  coachId: string;
  coachName: string;
  planId: string | null;
  workout?: Block[];
  participants: {
    id: string;
    name: string;
    helpRequested: boolean;
    metric: MetricView | null;
    summary: {
      totalReps: number;
      totalHoldSeconds?: number;
      trackedSamples: number;
      scoreTotal: number;
    } | null;
  }[];
};
export type WorkspaceData = {
  features?: import('./coaching-features').CoachingFeatures;
  customExercises?: ExerciseDefinition[];
  coaches?: { id: string; name: string }[];
  permissions?: {
    admin: boolean;
    coach: boolean;
    trainee: boolean;
    role: 'admin' | 'coach' | 'trainee';
  };
  user: Person;
  studio: { id: string; name: string } | null;
  clients: ClientView[];
  plans: Plan[];
  classes: ClassView[];
  billing: string;
  services: { video: boolean; billing: boolean; email: boolean };
  demo: boolean;
  workoutSets: WorkoutSetView[];
  checkIns: CheckInView[];
  assignments: AssignmentView[];
};
export type MessageView = {
  id: string;
  senderId: string;
  senderName: string;
  recipientId: string | null;
  text: string;
  kind: string;
  createdAt: string;
};
