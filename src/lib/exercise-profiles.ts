export type ExerciseProfile = {
  name: string;
  category: string;
  joints: number[];
  signal: 'knee' | 'elbow' | 'body' | 'shoulder' | 'hip';
  direction: 'decrease' | 'increase';
  view: 'side' | 'front' | 'either';
  form:
    | 'squat'
    | 'pushup'
    | 'curl'
    | 'plank'
    | 'lunge'
    | 'press'
    | 'lateralraise'
    | 'jumpingjack'
    | 'bridge'
    | 'crunch'
    | 'row'
    | 'sideplank'
    | 'frontraise'
    | 'stepjack'
    | 'hinge'
    | 'overhead'
    | 'bandrow'
    | 'wallsit'
    | 'highknees';
  bilateral: boolean;
  isHold: boolean;
  topAngle: number;
  bottomAngle: number;
  minimumRom: number;
  hysteresis: number;
  minRepMs: number;
  maxRepMs: number;
  cooldownMs: number;
  occlusionGraceMs: number;
  startCue: string;
  moveCue: string;
  returnCue: string;
  cameraCue: string;
  /** Library equipment text. */
  equipment?: string;
  /** Left/right limb modes run each limb as its own cycle (curl modes, alternating legs). */
  limbModes?: 'arm' | 'leg';
  /** Landmark that ends the straight body line for push-up forms (27 ankle, 25 knee). */
  bodyLineJoint?: 25 | 27;
  /** Steepest shoulder-to-line slope, in degrees from horizontal, for push-up forms. */
  maxBodySlopeDeg?: number;
  /** Ankle width as a multiple of shoulder span at the closed and open endpoints. */
  feet?: { closed: number; open: number };
  /** Holds count while the angle stays between the configured bottom and top angles. */
  holdBand?: boolean;
  /** Suspend instead of using projected 2D angles, which cannot see this movement. */
  require3d?: boolean;
  /** Reject a rep when form was invalid on two adjacent frames anywhere in the cycle, not only at its end. */
  strictCycleForm?: boolean;
};

