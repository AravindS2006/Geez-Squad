// PreToolUse(Read|Edit|Write|MultiEdit|NotebookEdit): protect secrets, generated
// files and applied migrations. Applied migrations are append-only history.
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { block, isSecretFile, projectDir, projectPath, readInput } from './lib.mjs';

const input = await readInput();
const tool = input.tool_name;
const target = input.tool_input?.file_path || input.tool_input?.notebook_path;
const rel = projectPath(target);
if (!rel) process.exit(0);

if (isSecretFile(rel))
  block(
    `${rel} may hold credentials. Inspect configuration by key/status (see SECURITY.md); use .env.example / .env.production.example for the shape.`,
  );

if (tool === 'Read') process.exit(0);

const generated = [
  [
    /^prisma\/postgres\/schema\.prisma$/,
    'generated from prisma/schema.prisma by scripts/postgres.mjs',
  ],
  [/^public\/(models|wasm|vision)\//, 'generated by scripts/prepare-assets.mjs'],
  [/^(\.next|node_modules|test-results|playwright-report)\//, 'build/test output'],
  [/^(tsconfig\.tsbuildinfo|next-env\.d\.ts|package-lock\.json)$/, 'generated by tooling'],
];
for (const [pattern, why] of generated)
  if (pattern.test(rel)) block(`${rel} is ${why}. Edit the source it is generated from.`);

// Committed migrations may already be applied somewhere; a new, uncommitted one
// can still be edited while it is being written.
const migration = /^prisma\/(postgres\/)?migrations\/[^/]+\/migration\.sql$/;
if (migration.test(rel) && existsSync(resolve(projectDir, rel))) {
  const tracked = spawnSync('git', ['ls-files', '--error-unmatch', rel], {
    cwd: projectDir,
    stdio: 'ignore',
  });
  if (tracked.status === 0)
    block(
      `${rel} is a committed migration. Migrations are append-only: add a new timestamped directory in BOTH prisma/migrations and prisma/postgres/migrations (see the schema-change skill).`,
    );
}
